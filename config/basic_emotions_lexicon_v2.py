def search_emotion_lexicon(query):
    """Cari kata dalam emotion lexicon"""
    results = {}
    query_lower = query.lower()
    for word, score in BASIC_EMOTIONS_LEXICON.items():
        if query_lower in word.lower():
            results[word] = {
                'score': score,
                'category': get_emotion_category(word)
            }
    return results

